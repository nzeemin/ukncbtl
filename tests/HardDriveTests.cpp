// HardDriveTests.cpp : tests for the IDE hard drive and its disk image files
//
// The images are generated by the tests in the temp directory. The drive is used through its IDE
// ports the way a driver does it: set the cylinder, head, sector and count, send the command, wait
// until the buffer is ready, then transfer the words of the sector.
//
// Polarity: the image is stored either "non-inverted" (the file words are the data) or "inverted"
// (the file words are complemented, which the drive detects by the first sector). The data port
// of the drive gives the complement of the words of a non-inverted image ("QBUS inverts the bits",
// see the comments in Hard.cpp); an inverted image of the same disk gives the same words.
// Tests of the known bugs are ignored, see the list in docs/unit-tests.md.

#include "stdafx.h"
#include <CppUnitTest.h>
