// IDE ports of the drive
const uint16_t PORT_DATA = 0x1F0;
const uint16_t PORT_ERROR = 0x1F1;
const uint16_t PORT_COUNT = 0x1F2;
const uint16_t PORT_SECTOR = 0x1F3;
const uint16_t PORT_CYL_LSB = 0x1F4;
const uint16_t PORT_CYL_MSB = 0x1F5;
const uint16_t PORT_HEAD = 0x1F6;
const uint16_t PORT_STATUS = 0x1F7;   // status when read, command when written

const uint8_t STATUS_ERROR = 0x01;
const uint8_t STATUS_DRQ = 0x08;      // data request: the buffer is ready for the transfer
const uint8_t STATUS_SEEK_DONE = 0x10;
const uint8_t STATUS_READY = 0x40;
const uint8_t STATUS_BUSY = 0x80;

const uint8_t CMD_READ = 0x20;
const uint8_t CMD_WRITE = 0x30;
const uint8_t CMD_SET_CONFIG = 0x91;
const uint8_t CMD_IDENTIFY = 0xEC;

struct Geometry
{
    int cylinders, heads, sectors;
    int Total() const { return cylinders * heads * sectors; }
};

const Geometry GEO = { 4, 2, 8 };       // 64 sectors, 32 KB

// A non-inverted image: the first sector carries the sectors per track and the heads in its first two bytes
std::vector<uint8_t> MakeHardImage(const Geometry& g)
{
    std::vector<uint8_t> image((size_t) g.Total() * 512);
    for (size_t i = 0; i < image.size(); i++)
        image[i] = (uint8_t) ((i / 512) * 7 + (i % 512) * 3 + 5);
    image[0] = (uint8_t) g.sectors;
    image[1] = (uint8_t) g.heads;
    for (int i = 0x1F0; i <= 0x1FB; i++)
        image[i] = 0;  // not all ones, so the image is not detected as inverted
    return image;
}

std::vector<uint8_t> Invert(const std::vector<uint8_t>& image)
{
    std::vector<uint8_t> result(image.size());
    for (size_t i = 0; i < image.size(); i++)
        result[i] = (uint8_t) ~image[i];
    return result;
}

// The word the data port gives for the word k of the sector lba of the non-inverted image
uint16_t PortWord(const std::vector<uint8_t>& image, int lba, int k)
{
    size_t offset = (size_t) lba * 512 + k * 2;
    return (uint16_t) ~(uint16_t) (image[offset] | (image[offset + 1] << 8));
}

// Drive that is attached and has finished the reset
void StartDrive(CHardDrive& hd, const TCHAR* path)
{
    Assert::IsTrue(hd.AttachImage(path), _T("attach"));
    hd.Reset();
    hd.Periodic();
    hd.Periodic();
}

uint8_t Status(CHardDrive& hd) { return (uint8_t) (hd.ReadPort(PORT_STATUS) & 0xFF); }

// Wait until the drive is not busy, return the status
uint8_t WaitNotBusy(CHardDrive& hd)
{
    for (int i = 0; i < 5000; i++)
    {
        uint8_t status = Status(hd);
        if ((status & STATUS_BUSY) == 0)
            return status;
        hd.Periodic();
    }
    Assert::Fail(_T("the drive stays busy"));
    return 0;
}

void SetupChs(CHardDrive& hd, int cylinder, int head, int sector, int count)
{
    hd.WritePort(PORT_HEAD, (uint16_t) head);
    hd.WritePort(PORT_CYL_LSB, (uint16_t) (cylinder & 0xFF));
    hd.WritePort(PORT_CYL_MSB, (uint16_t) (cylinder >> 8));
    hd.WritePort(PORT_SECTOR, (uint16_t) sector);
    hd.WritePort(PORT_COUNT, (uint16_t) count);
}

// Transfer 256 words from the data port; the buffer has to be ready
void ReadWords(CHardDrive& hd, uint16_t* words)
{
    for (int i = 0; i < 256; i++)
        words[i] = hd.ReadPort(PORT_DATA);
}

bool SectorEquals(const uint16_t* words, const std::vector<uint8_t>& image, int lba)
{
    for (int k = 0; k < 256; k++)
        if (words[k] != PortWord(image, lba, k)) return false;
    return true;
}

// Read the sectors one after another with one command
bool ReadSectors(CHardDrive& hd, int cylinder, int head, int sector, int count, uint16_t* words)
{
    SetupChs(hd, cylinder, head, sector, count);
    hd.WritePort(PORT_STATUS, CMD_READ);
    for (int n = 0; n < count; n++)
    {
        uint8_t status = WaitNotBusy(hd);
        if ((status & STATUS_ERROR) != 0 || (status & STATUS_DRQ) == 0)
            return false;
        ReadWords(hd, words + n * 256);
    }
    return true;
}

void WriteSector(CHardDrive& hd, int cylinder, int head, int sector, const uint16_t* words)
{
    SetupChs(hd, cylinder, head, sector, 1);
    hd.WritePort(PORT_STATUS, CMD_WRITE);
    Assert::IsTrue((Status(hd) & STATUS_DRQ) != 0, _T("the drive asks for the data"));
    for (int i = 0; i < 256; i++)
        hd.WritePort(PORT_DATA, words[i]);
}

int LbaOf(const Geometry& g, int cylinder, int head, int sector /*1-based*/)
{
    return (cylinder * g.heads + head) * g.sectors + (sector - 1);
}

